"""Generate the MOSS 12px-line bitmap font from the installed 14px XiaoZhi font.

Requires Pillow only when regenerating; the firmware uses console_font.h directly.
"""

from pathlib import Path
import re

from PIL import Image


def main():
    assets = Path(__file__).resolve().parent
    root = assets.parents[3]
    source = root / "managed_components/78__xiaozhi-fonts/src/font_noto_sans_basic_14_1.c"
    text = source.read_text(encoding="utf-8")

    def array(name):
        match = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
        return re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S)

    def scaled(value):
        return (value * 3 + 2) // 4 if value >= 0 else -((-value * 3 + 2) // 4)

    bitmap = bytes(int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", array("glyph_bitmap")))
    glyphs = [dict((k, int(v)) for k, v in re.findall(r"\.(\w+)\s*=\s*(-?\d+)", entry))
              for entry in re.findall(r"\{([^{}]*)\}", array("glyph_dsc"))]
    packed = bytearray()
    descriptors = []
    for glyph in glyphs:
        width, height = glyph["box_w"], glyph["box_h"]
        new_width = max(1, scaled(width)) if width else 0
        new_height = min(12, max(1, scaled(height))) if height else 0
        offset = len(packed)
        if width and height:
            image = Image.new("L", (width, height))
            for y in range(height):
                for x in range(width):
                    bit = y * width + x
                    image.putpixel((x, y), 255 if bitmap[glyph["bitmap_index"] + bit // 8]
                                   & (1 << (7 - bit % 8)) else 0)
            image = image.resize((new_width, new_height), Image.Resampling.BOX)
            data = bytearray((new_width * new_height + 7) // 8)
            for y in range(new_height):
                for x in range(new_width):
                    if image.getpixel((x, y)) >= 96:
                        bit = y * new_width + x
                        data[bit // 8] |= 1 << (7 - bit % 8)
            packed.extend(data)
        ofs_y = max(-2, min(10 - new_height, scaled(glyph["ofs_y"])))
        descriptors.append(
            f"    {{.bitmap_index = {offset}, .adv_w = {scaled(glyph['adv_w'])}, "
            f".box_w = {new_width}, .box_h = {new_height}, "
            f".ofs_x = {scaled(glyph['ofs_x'])}, .ofs_y = {ofs_y}}},")

    lines = ["// Generated by generate_console_font.py; do not edit by hand.",
             "// Derived from 78/xiaozhi-fonts font_noto_sans_basic_14_1 (uncompressed bitmap).",
             "#pragma once", "#include <lvgl.h>", "namespace moss_assets {",
             "inline const uint8_t glyph_bitmap[] = {"]
    for i in range(0, len(packed), 16):
        lines.append("    " + ", ".join(f"0x{value:02x}" for value in packed[i:i + 16]) + ",")
    lines.extend(["};", "inline const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"])
    lines.extend(descriptors)
    lines.append("};")
    for name in re.findall(r"static const uint16_t (unicode_list_\d+)\[\]", text):
        lines.extend([f"inline const uint16_t {name}[] = {{", array(name), "};"])
    lines.extend(["inline const lv_font_fmt_txt_cmap_t cmaps[] = {", array("cmaps"), "};",
                  "inline const lv_font_fmt_txt_dsc_t font_dsc = {",
                  "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,",
                  "    .kern_dsc = nullptr, .kern_scale = 0, .cmap_num = 10, .bpp = 1,",
                  "    .kern_classes = 0, .bitmap_format = 0,", "};",
                  "inline const lv_font_t kConsoleFont = [] {",
                  "    lv_font_t font{};",
                  "    font.get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt;",
                  "    font.get_glyph_bitmap = lv_font_get_bitmap_fmt_txt;",
                  "    font.line_height = 12; font.base_line = 2;",
                  "    font.subpx = LV_FONT_SUBPX_NONE; font.kerning = LV_FONT_KERNING_NONE;",
                  "    font.underline_position = -1; font.underline_thickness = 1;",
                  "    font.dsc = &font_dsc; return font;", "}();",
                  "}  // namespace moss_assets", ""])
    (assets / "console_font.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated 12px-line font: {len(glyphs)} glyphs, {len(packed)} bitmap bytes")


if __name__ == "__main__":
    main()
